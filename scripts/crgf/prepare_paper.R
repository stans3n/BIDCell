# Fixed reference preparation. Never retrain from a method's spatial labels.
args <- commandArgs(trailingOnly=TRUE)
p <- jsonlite::fromJSON(args[1], simplifyVector=FALSE); out <- args[2]
dir.create(out,recursive=TRUE,showWarnings=FALSE)
suppressPackageStartupMessages(library(SingleCellExperiment))
suppressPackageStartupMessages(library(scClassify))
source(p$official_processing)
source(p$official_expression)
set.seed(p$seed)
sce <- readRDS(p$reference)
stopifnot(identical(assayNames(sce), 'logcounts'), nrow(sce)==307L, ncol(sce)==30365L)
x <- as.matrix(logcounts(sce)); labels <- as.character(sce$graph_cluster_anno)
stopifnot(all(is.finite(x)), !anyNA(labels), length(unique(labels))==17L, !anyDuplicated(rownames(x)))
types <- unique(labels)
map <- setNames(types,types)
for(k in names(p$label_mapping)) {stopifnot(k %in% types); map[k] <- p$label_mapping[[k]]}
write.csv(data.frame(raw_label=types,evaluation_label=unname(map),mapping_version=p$mapping_version),file.path(out,'type_mapping.csv'),row.names=FALSE)
writeLines(rownames(x),file.path(out,'reference_genes.txt'))
means <- sapply(types,function(t)rowMeans(x[,labels==t,drop=FALSE]))
detect <- sapply(types,function(t)rowMeans(x[,labels==t,drop=FALSE]>0))
colnames(means) <- colnames(detect) <- unname(map)
write.csv(means,file.path(out,'reference_mean_logcounts.csv'))
write.csv(detect,file.path(out,'reference_detection_proportions.csv'))
ref <- SingleCellExperiment(assays=list(mean=means,prop_detected=detect))
pos <- generateMarkerList(ref,q=p$markers$q,t=p$markers$positive_t,type='positive',verbose=FALSE)
neg <- generateMarkerList(ref,q=p$markers$q,t=p$markers$negative_t,type='negative',verbose=FALSE)
saveRDS(list(positive=pos,negative=neg),file.path(out,'markers.rds'))
jsonlite::write_json(list(positive=pos,negative=neg),file.path(out,'markers.json'),auto_unbox=FALSE,pretty=TRUE)
train <- do.call(scClassify::train_scClassify,c(list(exprsMat_train=x,cellTypes_train=labels),p$training))
saveRDS(train,file.path(out,'scClassify_model.rds'))
saveRDS(list(genes=rownames(x),map=map,types=unname(map)),file.path(out,'reference_metadata.rds'))
# Real fixed-reference predictions exercise the actual installed API before queue admission.
idx <- unlist(lapply(types,function(t)head(which(labels==t),2)))
pr <- do.call(scClassify::predict_scClassify,c(list(exprsMat_test=x[,idx,drop=FALSE],trainRes=train),p$prediction))[[1]]
saveRDS(pr,file.path(out,'reference_smoke_predictions.rds'))
stopifnot(length(pr$predRes)==length(idx), nrow(pr$predLabelMat)==length(idx))
write.csv(data.frame(cell_id=colnames(x)[idx],reference_label=labels[idx],prediction=pr$predRes),file.path(out,'reference_smoke_predictions.csv'),row.names=FALSE)
ip <- installed.packages(); write.csv(ip[,c('Package','Version','LibPath')],file.path(out,'R_packages.csv'),row.names=FALSE)
writeLines(capture.output(sessionInfo()),file.path(out,'R_sessionInfo.txt'))
writeLines('succeeded',file.path(out,'execution_status.txt'))
