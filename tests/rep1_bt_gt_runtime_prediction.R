args <- commandArgs(trailingOnly=TRUE)
out <- args[[1]]; cursor <- as.integer(args[[2]]); total <- as.integer(args[[3]])
folder <- file.path(out, "prediction_chunks"); dir.create(folder, recursive=TRUE, showWarnings=FALSE)
target <- file.path(folder, sprintf("batch_%04d.rds", cursor))
saveRDS(list(engineering_only=TRUE, cursor=cursor, values=seq_len(cursor)^2), paste0(target, ".tmp"))
file.rename(paste0(target, ".tmp"), target)
meta <- list(file=target, dependencies_digest=args[[4]], cursor=cursor, total=total)
pending <- file.path(folder, sprintf("batch_%04d.pending.json", cursor))
jsonlite::write_json(meta, paste0(pending, ".tmp"), auto_unbox=TRUE)
file.rename(paste0(pending, ".tmp"), pending)
cat(cursor, "\n", file=file.path(out, "prediction_visits.txt"), append=TRUE, sep="")
writeLines("succeeded", file.path(out, "execution_status.txt"))
